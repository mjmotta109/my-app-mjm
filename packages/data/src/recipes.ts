import type { DietTag, Difficulty, MealSlot, PrepInfo, Recipe, RecipeIngredient, Unit } from "@rinde/core";

/**
 * Recetario demo.
 *
 * Cocina colombiana de diario más platos de otras cocinas resueltos con
 * ingredientes que se consiguen en cualquier plaza o supermercado del país.
 * El criterio no es la bandera del plato: es que se pueda cocinar aquí, con lo
 * que hay y con lo que cuesta.
 *
 * Las cantidades están escritas para `baseServings` porciones; el motor las
 * escala al hogar. Los ingredientes marcados como opcionales no generan
 * compra: solo se usan si ya están en la despensa.
 *
 * `nutritionIsEstimated` es `true` en todas: la nutrición se calcula sumando
 * ingredientes crudos. Ver `nutrition-note.ts`.
 */

// ---------------------------------------------------------------------------
// Comportamiento en cocina por adelantado
// ---------------------------------------------------------------------------

/*
 * `keepsDays` cuenta el día en que se cocina como el primero: 3 días significa
 * "hoy, mañana y pasado mañana". Son valores prudentes de manejo doméstico, no
 * un análisis microbiológico; ante la duda, menos días.
 */

/** Guisos, sudados y salsas: mejoran de un día para otro y congelan bien. */
const GUISO: PrepInfo = { batchFriendly: true, keepsDays: 3, freezable: true };

/** Granos y legumbres cocidos: lo que mejor aguanta de toda la cocina. */
const GRANO: PrepInfo = { batchFriendly: true, keepsDays: 4, freezable: true };

/** Sopas y cremas. */
const SOPA: PrepInfo = { batchFriendly: true, keepsDays: 3, freezable: true };

/** Arroces y pastas ya cocidos: aguantan menos que un guiso. */
const ALMIDON: PrepInfo = { batchFriendly: true, keepsDays: 2, freezable: true };

/** Horneados de carne o verdura. */
const HORNO: PrepInfo = { batchFriendly: true, keepsDays: 3, freezable: true };

/** Nada que hacer por adelantado: solo queda bien recién hecho. */
const AL_MOMENTO: PrepInfo = {
  batchFriendly: false,
  keepsDays: 1,
  freezable: false,
  finishNote: "Se hace en el momento: recalentado pierde por completo la gracia.",
};

/** Frituras: recalentadas quedan blandas y aceitosas. */
const FRITO: PrepInfo = {
  batchFriendly: false,
  keepsDays: 1,
  freezable: false,
  finishNote: "Fríelo al momento; guardado se ablanda.",
};

/** Crudos y ensaladas. */
const CRUDO: PrepInfo = {
  batchFriendly: false,
  keepsDays: 1,
  freezable: false,
  finishNote: "Pica y aliña justo antes de servir.",
};

/** El guiso se adelanta; lo que lo acompaña se arma al servir. */
const GUISO_ARMAR: PrepInfo = {
  batchFriendly: true,
  keepsDays: 3,
  freezable: true,
  finishNote: "Adelanta el relleno o el guiso; arma el plato al momento de servir.",
};

type Ing = [id: string, qty: number, unit: Unit, optional?: boolean];

function recipe(
  id: string,
  name: string,
  description: string,
  slots: MealSlot[],
  baseServings: number,
  minutes: number,
  difficulty: Difficulty,
  tags: DietTag[],
  ings: Ing[],
  steps: string[],
  prep: PrepInfo = GUISO,
  region = "Colombia",
): Recipe {
  const ingredients: RecipeIngredient[] = ings.map(([ingredientId, qty, unit, optional]) => ({
    ingredientId,
    qty,
    unit,
    ...(optional ? { optional: true } : {}),
  }));
  return {
    id, name, description, baseServings, slots, minutes, difficulty, region, tags,
    ingredients, steps, nutritionIsEstimated: true, prep,
  };
}

