import type { DietTag, Difficulty, MealSlot, Recipe, RecipeIngredient, Unit } from "@rinde/core";

/**
 * Recetario demo: cocina colombiana de diario y platos económicos.
 *
 * Las cantidades están escritas para `baseServings` porciones; el motor las
 * escala al hogar. Los ingredientes marcados como opcionales no generan compra:
 * solo se usan si ya están en la despensa.
 *
 * `nutritionIsEstimated` es `true` en todas: la nutrición se calcula sumando
 * ingredientes crudos. Ver `nutrition-note.ts`.
 */

type Ing = [id: string, qty: number, unit: Unit, optional?: boolean];

function recipe(
  id: string,
  name: string,
  description: string,
  slots: MealSlot[],
  baseServings: number,
  minutes: number,
  difficulty: Difficulty,
  tags: DietTag[],
  ings: Ing[],
  steps: string[],
  region = "Colombia",
): Recipe {
  const ingredients: RecipeIngredient[] = ings.map(([ingredientId, qty, unit, optional]) => ({
    ingredientId,
    qty,
    unit,
    ...(optional ? { optional: true } : {}),
  }));
  return {
    id, name, description, baseServings, slots, minutes, difficulty, region, tags,
    ingredients, steps, nutritionIsEstimated: true,
  };
}

